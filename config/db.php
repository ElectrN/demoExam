<?php
// ============================================================
// КОНФИГУРАЦИЯ ПОДКЛЮЧЕНИЯ К БАЗЕ ДАННЫХ (PDO)
// ============================================================

// Параметры подключения к MySQL
$host = 'localhost';        // Хост базы данных
$db = 'demoTrainin';        // Имя базы данных
$user = 'root';             // Логин MySQL (по умолчанию в XAMPP)
$pass = '';                 // Пароль (пустой в XAMPP)
$charset = 'utf8mb4';       // Кодировка для поддержки кириллицы

// Формируем DSN-строку для PDO (используем двойные кавычки для интерполяции переменных)
$dsn = "mysql:host=$host;dbname=$db;charset=$charset";

// Настройки PDO для безопасности и удобства работы
$options = [
    // Выбрасывать исключения при ошибках SQL (удобно для отладки)
    PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
    // Возвращать результаты запросов как ассоциативные массивы
    PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,
    // Использовать настоящие подготовленные выражения (защита от инъекций)
    PDO::ATTR_EMULATE_PREPARES => false,
];

// Пытаемся создать подключение к базе данных
try {
    $pdo = new PDO($dsn, $user, $pass, $options);
} catch (PDOException $e) {
    // При ошибке подключения возвращаем JSON-ответ с кодом 500
    http_response_code(500);
    echo json_encode(['error' => 'Ошибка подключения к базе данных']);
    exit; // Прекращаем выполнение скрипта
}